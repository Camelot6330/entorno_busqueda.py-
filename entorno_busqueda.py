    print("\n--- 2. Pruebas de Acciones Legales ---")
    # Esquina superior izquierda (restringido por bordes y muro debajo)
    estado_prueba = (0, 0)
    print(f"Acciones desde el inicio {estado_prueba}: {entorno.acciones(estado_prueba)}")

    # Casilla con muros a izquierda y derecha (solo se mueve en vertical)
    estado_prueba = (1, 2)
    print(f"Acciones desde {estado_prueba} (muros laterales): {entorno.acciones(estado_prueba)}")

    # Casilla con muro debajo
    estado_prueba = (2, 2)
    print(f"Acciones desde {estado_prueba} (muro abajo): {entorno.acciones(estado_prueba)}")

    # Esquina inferior derecha (la meta, limitada por bordes)
    estado_prueba = (4, 4)
    print(f"Acciones desde la meta {estado_prueba}: {entorno.acciones(estado_prueba)}")

    print("\n--- 3. Pruebas del Modelo de Transición ---")
    estado = (0, 0)
    for accion in entorno.acciones(estado):
        print(f"Desde {estado}, '{accion}' -> {entorno.modelo_transicion(estado, accion)}")

    estado = (2, 2)
    for accion in entorno.acciones(estado):
        print(f"Desde {estado}, '{accion}' -> {entorno.modelo_transicion(estado, accion)}")

    print("\n--- 4. Recorrido manual de inicio a meta ---")
    estado = entorno.estado_inicial
    ruta = ['DERECHA', 'DERECHA', 'ABAJO', 'ABAJO', 'DERECHA', 'DERECHA', 'ABAJO', 'ABAJO']
    costo_total = 0
    for accion in ruta:
        if accion in entorno.acciones(estado):
            siguiente = entorno.modelo_transicion(estado, accion)
            costo_total += entorno.costo_ruta(estado, accion, siguiente)
            print(f"{estado} --{accion}--> {siguiente}")
            estado = siguiente
        else:
            print(f"Acción ilegal '{accion}' desde {estado}")
            break
    print(f"¿Llegó a la meta?: {entorno.prueba_meta(estado)} | Costo total: {costo_total}")